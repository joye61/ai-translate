// Rebuild src/AiTranslate.Desktop/FontAwesomeIconPaths.cs from the Font Awesome Free SVG sources (https://fontawesome.com/icons).
//
//   npm install --prefix <tmp> @fortawesome/fontawesome-free
//   node tools/generate-fontawesome-icons.mjs <tmp>/node_modules/@fortawesome/fontawesome-free
//
// Add a name to ICONS ("name" is the solid style, "regular/name" the regular style), run the script, then use that
// exact name with FontAwesomeIcon. Only icons in the Free set exist; Pro-only names make the script fail.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS = [
  // 方向与折叠
  "arrow-left", "arrow-right", "arrow-up", "chevron-down", "chevron-up",
  // 窗口控制
  "compress", "expand", "regular/window-maximize", "regular/window-restore", "window-minimize", "xmark",
  // 通用操作
  "arrows-rotate", "check", "check-double", "circle-check", "circle-info", "circle-xmark", "ellipsis", "floppy-disk",
  "folder", "folder-open", "gear", "pencil", "plus", "power-off", "regular/copy", "regular/image", "regular/trash-can",
  "share-from-square", "stop",
  // 采集入口
  "crop-simple", "i-cursor", "paste",
  // 词典与生词本
  "book", "book-bookmark", "book-open", "bookmark", "brain", "database", "globe", "hourglass-half", "language",
  "layer-group", "quote-left", "regular/bookmark", "regular/keyboard", "regular/lightbulb", "tag", "wand-magic-sparkles",
  "eye", "eye-slash",
  // 语音
  "gauge", "microphone-lines", "repeat", "volume-high", "volume-low", "volume-off", "wave-square",
  // Grammar studio
  "circle-question", "clock-rotate-left", "graduation-cap", "lightbulb", "list-check", "magnifying-glass",
  "pen-to-square", "scale-balanced", "sitemap", "triangle-exclamation",
];

const source = resolve(process.argv[2] ?? "node_modules/@fortawesome/fontawesome-free");
const output = resolve(dirname(fileURLToPath(import.meta.url)), "../src/AiTranslate.Desktop/FontAwesomeIconPaths.cs");

const entries = ICONS.map((icon) => {
  const svg = readFileSync(join(source, "svgs", `${icon.includes("/") ? icon : `solid/${icon}`}.svg`), "utf8");
  const [, width, height] = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  const parts = [...svg.matchAll(/<path\b[^>]*?\bd="([^"]+)"/g)].map((m) => m[1].trim());
  if (parts.length === 0) throw new Error(`No path in ${icon}`);
  // A relative moveto is only absolute at the start; anchor later parts so joining cannot shift them.
  const joined = parts.map((part, i) => (i > 0 && part.startsWith("m") ? `M0 0${part}` : part)).join("");
  return `        ["${icon}"] = new(${width}, ${height}, "${joined}"),`;
});

const version = JSON.parse(readFileSync(join(source, "package.json"), "utf8")).version;
writeFileSync(output, `// <auto-generated>
// Generated by tools/generate-fontawesome-icons.mjs from Font Awesome Free ${version} (https://fontawesome.com/icons). Do not edit by hand.
// Icons: CC BY 4.0, see Assets/Brand/LICENSE-FONTAWESOME.txt.
// </auto-generated>
namespace AiTranslate.Desktop;

public static partial class FontAwesomeIconLibrary
{
    // Each entry is the filled glyph of a Font Awesome Free SVG with its own viewBox size (most are 512 high).
    private static readonly Dictionary<string, IconShape> Shapes = new(StringComparer.OrdinalIgnoreCase)
    {
${entries.join("\n")}
    };
}
`);
console.log(`Wrote ${ICONS.length} icons from Font Awesome Free ${version}`);
